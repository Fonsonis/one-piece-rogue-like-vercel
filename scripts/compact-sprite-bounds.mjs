import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
const root = new URL('../', import.meta.url);
const sizing = JSON.parse(fs.readFileSync(new URL('docs/sprite-sizing.json',root)));
const motion = JSON.parse(fs.readFileSync(new URL('docs/motion-bounds.json',root)));

// Combat retains the four atlas poses, without extra rotation, stretch or lunge.
export function compactBounds(id) {
  const {atlasScale:s,guardBounds:g} = sizing[id];
  const center=(g[0]+g[2])/2;
  const boxes=motion[id].frames;
  const left=Math.min(...boxes.map(b=>(b[0]-center)*s))-3;
  const right=Math.max(...boxes.map(b=>(b[2]-center)*s))+3;
  const top=-Math.min(...boxes.map(b=>(b[1]-180.48)*s+.48))+3;
  const bottom=Math.max(0,...boxes.map(b=>(b[3]-180.48)*s+.48))+3;
  return {x:192/(right-left),y:192/(top+bottom),floor:bottom/192,center:(right+left)/384};
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const lines=['/* Generated by scripts/compact-sprite-bounds.mjs: all four poses, no added transforms. */'];
  for(const id of Object.keys(sizing)) {
    const b=compactBounds(id);
    lines.push(`.battle-layout [data-character="${id}"]{--motion-fit-x:${b.x.toFixed(8)};--motion-fit-y:${b.y.toFixed(8)};--motion-floor:${b.floor.toFixed(8)};--motion-center:${b.center.toFixed(8)}}`);
  }
  fs.writeFileSync(new URL('public/art/compact-sprite-bounds.css',root),lines.join('\n')+'\n');
}
